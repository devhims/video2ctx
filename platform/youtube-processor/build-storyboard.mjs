import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// A narrow, reproducible bundle lets hosted storyboard fixes deploy with this repo.
// Other provider operations still use the pinned npm library. No credentials enter it.
const output = new URL('./storyboard-extractor.mjs', import.meta.url);
const result = await build({
  absWorkingDir: fileURLToPath(new URL('../..', import.meta.url)),
  stdin: { contents: "export { getStoryboardWithFallback } from './packages/all-things-youtube/src/storyboard-client'; export { readBoundedBytes } from './packages/all-things-youtube/src/storyboard'; export { YouTubeClientError } from './packages/all-things-youtube/src/youtube-types';",
    resolveDir: fileURLToPath(new URL('../..', import.meta.url)), sourcefile: 'storyboard-entry.ts' },
  bundle: true, write: false, platform: 'node', target: 'node22', format: 'esm',
  banner: { js: '// Generated by npm --prefix platform/youtube-processor run bundle. Edit shared source, not this file.' },
  footer: { js: `/* all-things-youtube\n${(await readFile(new URL('../../packages/all-things-youtube/LICENSE', import.meta.url), 'utf8')).replaceAll('*/', '* /')}*/` },
});
const bytes = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  if (!Buffer.from(bytes).equals(await readFile(output))) throw new Error('Storyboard bundle is stale. Run npm --prefix platform/youtube-processor run bundle.');
} else await writeFile(output, bytes);
